import matplotlib.pyplot as plt
import numpy as np

fig, ax = plt.subplots(subplot_kw={"projection": "3d"})

u = np.linspace(0, 4 * np.pi, 100)
v = np.linspace(0.001, 2, 100)
u, v = np.meshgrid(u, v)

x = np.cos(u) * np.sin(v)
y = np.sin(u) * np.sin(v)
z = np.cos(v) + np.log(np.tan(v / 2)) + 0.2 * u - 4

ax.plot_surface(x, y, z, color="r", edgecolor="g", alpha=0.7)
plt.show()

