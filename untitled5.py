v = np.linspace(-np.pi, np.pi, 100)
u, v = np.meshgrid(u, v)

x = u * np.cos(u) * (np.cos(v) + 1)
y = u * np.sin(u) * (np.cos(v) + 1)
z = u * np.sin(v)

